"""Record-to-Code Compiler for Sentinel Studio.

Transforms live autonomous or manual interactions into permanent, deterministic
Sentinel TestCase specifications and headless Python/Playwright test suites for CI/CD.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from sentinel.computer_use.dual_grounding import GroundedAction
from sentinel.core.schemas import ExpectedResult, TestCase, TestStep


class ActionRecorder:
    """Records real-time UI interactions and compiles them into reusable test cases."""

    def __init__(self, suite_name: str = "Studio Recorded Suite") -> None:
        self.suite_name = suite_name
        self.actions: list[GroundedAction] = []
        self.assertions: list[str] = []

    def record(self, action: GroundedAction) -> None:
        """Add an action to the recorded session trace."""
        self.actions.append(action)

    def add_assertion(self, assertion: str) -> None:
        """Add an assertion check to the recorded session."""
        self.assertions.append(assertion)

    def clear(self) -> None:
        """Reset the recorder."""
        self.actions.clear()
        self.assertions.clear()

    def to_test_case(self, test_id: str = "TC-REC-001", title: str = "Studio Interactive Test") -> TestCase:
        """Compile recorded session into a standard Sentinel TestCase."""
        steps: list[TestStep] = []

        for idx, act in enumerate(self.actions, start=1):
            step_action = act.action_type
            step_path = act.selector or str(act.value or "")
            body_val = None
            metadata = dict(act.metadata)

            if act.action_type in ("click", "tap"):
                step_action = "click"
                step_path = act.selector or f"coords({act.x},{act.y})"
            elif act.action_type in ("fill", "type", "input"):
                step_action = "fill"
                step_path = act.selector or ""
                body_val = str(act.value or "")
            elif act.action_type in ("navigate", "goto", "open"):
                step_action = "navigate"
                step_path = str(act.value or "")
            elif act.action_type in ("press", "key"):
                step_action = "press"
                step_path = act.selector or "body"
                metadata["key"] = str(act.value or "Enter")
            elif act.action_type == "wait":
                step_action = "wait"
                metadata["seconds"] = float(act.value or 1.0)

            steps.append(
                TestStep(
                    action=step_action,
                    path=step_path,
                    body=body_val,
                    metadata=metadata,
                )
            )

        # Build expected result assertions
        assertions = list(self.assertions)
        if not assertions:
            assertions.append("status_code == 200")

        expected = ExpectedResult(
            oracle="deterministic",
            assertions=assertions,
        )

        return TestCase(
            id=test_id,
            target_type="web",
            title=title,
            description=f"Generated by Sentinel Studio interactive recorder ({len(steps)} steps).",
            steps=steps,
            expected=expected,
            source_context=f"studio_recording://{self.suite_name}",
        )

    def export_yaml(self, output_path: Path | None = None) -> str:
        """Export recorded session as standard Sentinel YAML test suite."""
        tc = self.to_test_case()
        raw_dict = {
            "test_cases": [tc.model_dump(mode="json")],
        }
        yaml_str = yaml.dump(raw_dict, sort_keys=False, indent=2)

        if output_path:
            output_path = Path(output_path)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(yaml_str, encoding="utf-8")

        return yaml_str

    def export_playwright_python(self, output_path: Path | None = None) -> str:
        """Export recorded session as a native, headless pytest-playwright Python script."""
        lines = [
            '"""Auto-generated Playwright test script from Sentinel Studio."""',
            "from playwright.sync_api import Page, expect",
            "",
            "def test_recorded_interactive_flow(page: Page):",
        ]

        for act in self.actions:
            if act.action_type == "navigate":
                lines.append(f'    page.goto("{act.value}")')
            elif act.action_type == "click":
                if act.selector:
                    lines.append(f'    page.locator("{act.selector}").click()')
                elif act.x is not None and act.y is not None:
                    lines.append(f'    page.mouse.click({act.x}, {act.y})')
            elif act.action_type == "fill":
                clean_val = str(act.value or "").replace('"', '\\"')
                lines.append(f'    page.locator("{act.selector}").fill("{clean_val}")')
            elif act.action_type == "press":
                lines.append(f'    page.keyboard.press("{act.value or "Enter"}")')
            elif act.action_type == "wait":
                ms = int(float(act.value or 1.0) * 1000)
                lines.append(f'    page.wait_for_timeout({ms})')

        for assertion in self.assertions:
            lines.append(f"    # Assertion: {assertion}")

        code = "\n".join(lines) + "\n"

        if output_path:
            output_path = Path(output_path)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(code, encoding="utf-8")

        return code
